/** Terminal enters the 6-digit activation code generated by an admin -> receives a device token. */
r.post('/devices/activate', activateLimiter, async (req, res) => {
  const b = parse(z.object({ code: z.string().regex(/^[0-9]{6}$/), version: z.string().max(40).optional() }), req.body);
  const out = await tx(async (db) => {
    const d = await one(db, `SELECT * FROM devices WHERE activation_code = $1 AND activation_expires_at > now() FOR UPDATE`, [b.code]);
    if (!d) { logger.security.warn('device.bad_activation', { ip: req.ip }); throw fail('NOT_FOUND', 'Invalid or expired activation code'); }
    if (d.status === 'BLOCKED') throw fail('DEVICE_BLOCKED');
    const token = randomToken(32);
    await db.query('UPDATE devices SET token_hash = $2, activation_code = NULL, activation_expires_at = NULL, ip = $3, version = $4, online = true, last_online_at = now() WHERE id = $1', [d.id, sha256(token), req.ip, b.version || null]);
    await audit(db, { device: d, ip: req.ip }, { action: 'DEVICE_ACTIVATED', targetType: 'device', targetId: d.id, targetLabel: d.device_code });
    logger.device.info('device.activated', { deviceId: d.id, type: d.type });
    return { token, device: { id: d.id, code: d.device_code, type: d.type, name: d.name } };
  });
  res.json(out);
});

