r.post('/devices/:id/activation-code', requireStaff, perm('device.manage'), async (req, res) => {
  const out = await tx(async (db) => {
    let code;
    for (let i = 0; i < 10; i++) { code = randomDigits(6); if (!(await one(db, 'SELECT 1 FROM devices WHERE activation_code = $1', [code]))) break; }
    const d = await one(db, `UPDATE devices SET activation_code = $2, activation_expires_at = now() + interval '15 minutes' WHERE id = $1 AND status <> 'BLOCKED' RETURNING id, device_code, activation_expires_at`, [req.params.id, code]);
    if (!d) throw fail('NOT_FOUND', 'Device not found or blocked');
    await audit(db, req.ctx, { action: 'DEVICE_ACTIVATION_CODE', targetType: 'device', targetId: d.id, targetLabel: d.device_code });
    return { code, expiresAt: d.activation_expires_at };
  });
  res.json(out);
});
for (const [p, status] of [['block', 'BLOCKED'], ['unblock', 'ACTIVE'], ['deactivate', 'INACTIVE']]) {
  r.post(`/devices/:id/${p}`, requireStaff, perm('device.manage'), async (req, res) => {
    const b = parse(z.object({ reason: z.string().max(300).optional() }), req.body || {});
    if (status === 'BLOCKED' && !b.reason) throw fail('VALIDATION_ERROR', 'Reason is required');
    await tx(async (db) => {
      const d = await one(db, `UPDATE devices SET status = $2, block_reason = $3, token_hash = CASE WHEN $2 = 'ACTIVE' THEN token_hash ELSE NULL END, online = CASE WHEN $2 = 'ACTIVE' THEN online ELSE false END WHERE id = $1 RETURNING *`, [req.params.id, status, b.reason || null]);
      if (!d) throw fail('NOT_FOUND');
      await audit(db, req.ctx, { action: `DEVICE_${p.toUpperCase()}`, targetType: 'device', targetId: d.id, targetLabel: d.device_code, reason: b.reason });
      db.afterCommit(() => emit([`device:${d.id}`], 'device:revoked', { status }));
    });
    res.json({ ok: true });
  });
}

