const MIME = {
  'image/png': 'IMAGE', 'image/jpeg': 'IMAGE', 'image/webp': 'IMAGE', 'image/gif': 'IMAGE', 'image/svg+xml': 'IMAGE', 'image/x-icon': 'IMAGE', 'image/vnd.microsoft.icon': 'IMAGE',
  'video/mp4': 'VIDEO', 'video/webm': 'VIDEO', 'font/ttf': 'FONT', 'font/otf': 'FONT', 'font/woff': 'FONT', 'font/woff2': 'FONT',
  'application/x-font-ttf': 'FONT', 'application/x-font-otf': 'FONT', 'application/font-woff': 'FONT', 'application/vnd.ms-opentype': 'FONT',
  'audio/mpeg': 'SOUND', 'audio/wav': 'SOUND', 'audio/x-wav': 'SOUND', 'audio/ogg': 'SOUND', 'audio/webm': 'SOUND', 'application/pdf': 'DOCUMENT',
};
const EXT_KIND = { '.ttf': 'FONT', '.otf': 'FONT', '.woff': 'FONT', '.woff2': 'FONT', '.mp3': 'SOUND', '.wav': 'SOUND', '.ogg': 'SOUND' };
const FONT_MIME = { '.ttf': 'font/ttf', '.otf': 'font/otf', '.woff': 'font/woff', '.woff2': 'font/woff2' };
const upload = multer({
  storage: multer.diskStorage({
    destination: (_req, _f, cb) => { fs.mkdirSync(config.uploadDir, { recursive: true }); cb(null, config.uploadDir); },
    filename: (_req, file, cb) => cb(null, `${Date.now()}-${randomToken(8)}${path.extname(file.originalname).toLowerCase().replace(/[^.a-z0-9]/g, '')}`),
  }),
  limits: { fileSize: 200 * 1024 * 1024 },
  fileFilter: (_req, file, cb) => {
    const ext = path.extname(file.originalname).toLowerCase();
    if (MIME[file.mimetype] || EXT_KIND[ext]) return cb(null, true);
    cb(Object.assign(new Error(`File type not allowed: ${file.mimetype}`), { status: 415 }));
  },
});

