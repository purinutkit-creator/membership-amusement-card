/** Customer display -> POS input (language, member yes/no, phone, consent, card tap). */
r.post('/display/input', requireDisplay, async (req, res) => {
  const b = parse(z.object({ type: z.enum(['LANGUAGE', 'IS_MEMBER', 'PHONE', 'CONSENT', 'CARD', 'CANCEL']), value: z.any() }), req.body);
  const p = req.ctx.display;
  let extra = {};
  if (b.type === 'CONSENT') {
    const ids = Array.isArray(b.value?.policyIds) ? b.value.policyIds : [];
    for (const id of ids) await query('INSERT INTO privacy_consents(policy_id, device_id, pairing_id, language, ip, member_id) VALUES ($1,$2,$3,$4,$5,$6)', [id, p.display_device_id, p.id, b.value?.language || null, req.ip, b.value?.memberId || null]);
  }
  if (b.type === 'PHONE') {
    const phone = String(b.value || '').replace(/[^0-9+]/g, '');
    if (!/^\+?[0-9]{9,15}$/.test(phone)) throw fail('VALIDATION_ERROR', 'Invalid phone number');
    const m = await one({ query }, `SELECT id, first_name FROM members WHERE phone = $1 AND status = 'ACTIVE'`, [phone]);
    extra = { found: !!m, memberId: m?.id || null, firstName: m?.first_name || null };
    b.value = phone;
  }
  if (b.type === 'CARD') {
    const card = await findCard({ query }, String(b.value || '')).catch(() => null);
    extra = card ? { cardId: card.id, cardMemberId: card.member_id, cardNumber: `********${card.card_number.slice(-4)}`, balance: Number(card.balance), status: card.status } : { found: false };
    b.value = undefined;
  }
  emit([`staff:${p.staff_id}`], 'display:input', { pairingId: p.id, type: b.type, value: b.value, ...extra });
  res.json({ ok: true, ...extra });
});
